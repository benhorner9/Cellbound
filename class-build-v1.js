function bonusTalentName(spec,title){return String(spec)+' '+title}
function bonusTalentDefinitions(klass,spec){
 return (BONUS_TALENTS[roleFor(klass,spec)]||BONUS_TALENTS.dps).map(def=>({...def,id:bonusTalentName(spec,def.title)}))
}
function expandTalentTree(klass,spec,original){
 const nodes=(Array.isArray(original)?original:[]).map(n=>({...n}));
 const mainCapstone=nodes.find(n=>n.tier===4);
 if(mainCapstone)mainCapstone.exclusive='capstone';
 const secondary=nodes.find(n=>n.tier===3&&n.id!==mainCapstone?.req);
 const extras=bonusTalentDefinitions(klass,spec).map(def=>({
  id:def.id,icon:def.icon,tier:def.tier,col:3,max:def.max,
  req:def.tier===4?secondary?.id:undefined,exclusive:def.tier===4?'capstone':undefined,
  desc:def.desc,bonusEffect:def.effect,bonusAmount:def.amount
 }));
 return nodes.concat(extras)
}
function nodeState(character,spec,node,nodes){
 const ranks=character?.talents?.[spec]||{},rank=Math.max(0,Number(ranks[node.id])||0);
 const spent=talentSpent(character,spec),remaining=talentRemaining(character,spec);
 const complete=rank>=Math.max(1,Number(node.max)||1);
 const conflict=Boolean(node.exclusive&&(nodes||[]).some(other=>other.id!==node.id&&other.exclusive===node.exclusive&&Number(ranks[other.id])>0));
 const reqOk=!node.req||Number(ranks[node.req])>0,tierOk=spent>=tierRequirement(node.tier),available=reqOk&&tierOk&&!conflict;
 const reason=complete?'Maximum rank reached.':conflict?'Another capstone has already been chosen.':!reqOk?'Requires '+node.req+'.':!tierOk?'Requires '+tierRequirement(node.tier)+' points spent in this tree.':remaining<=0?'No build points available for this specialisation.':'Ready to invest.';
 return {rank,complete,available,canInvest:available&&!complete&&remaining>0,reason}
}
function migrateTalentBuilds(character,specNames=[]){
 if(!character||typeof character!=='object')return false;
 character.talents=character.talents&&typeof character.talents==='object'?character.talents:{};
 specNames.forEach(spec=>{if(!character.talents[spec])character.talents[spec]={}});
 if(character.talentSystemVersion===TALENT_SYSTEM_VERSION)return false;
 const wasInvested=Object.values(character.talents).some(ranks=>Object.values(ranks||{}).some(v=>Number(v)>0));
 specNames.forEach(spec=>{character.talents[spec]={}});
 character.talentSystemVersion=TALENT_SYSTEM_VERSION;
 if(wasInvested)character.talentRebuildNotice=true;
 syncLegacyTalentCounter(character);
 return wasInvested
}
const RESPEC_WINDOW_MS=86400000;
function respecStatus(character,member=false,now=Date.now()){
 const history=Array.isArray(character?.talentRespecHistory)?character.talentRespecHistory:[];
 const recent=history.filter(v=>Number.isFinite(Number(v))&&Number(v)>now-RESPEC_WINDOW_MS&&Number(v)<=now);
 const limit=member?3:1;
 return {used:recent.length,limit,remaining:Math.max(0,limit-recent.length),history:recent,nextAt:recent.length>=limit?Math.min(...recent)+RESPEC_WINDOW_MS:null}
}
function respec(character,spec,member=false,now=Date.now()){
 if(!character?.talents||!Object.prototype.hasOwnProperty.call(character.talents,spec)||talentSpent(character,spec)<=0)return false;
 const status=respecStatus(character,member,now);
 if(status.remaining<=0)return false;
 character.talents[spec]={};character.talentRespecHistory=status.history.concat(now);
 syncLegacyTalentCounter(character);
 return true
}
function talentBonuses(character){
 const spec=character?.spec,ranks=character?.talents?.[spec]||{},bonuses={};
 bonusTalentDefinitions(character?.class,spec).forEach(def=>{
  const rank=Math.max(0,Math.min(def.max,Math.floor(Number(ranks[def.id])||0)));
  if(rank)bonuses[def.effect]=(bonuses[def.effect]||0)+def.amount*rank
 });
 return bonuses
}

