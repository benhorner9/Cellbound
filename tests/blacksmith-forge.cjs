const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.resolve(__dirname,'..'),manifest=require('../tools/runtime-manifest.cjs');
const source=name=>fs.readFileSync(manifest.sourcePath(root,name),'utf8');
const sandbox={window:{}};vm.createContext(sandbox);
vm.runInContext(source('blacksmith-forge-v1.js'),sandbox,{filename:'blacksmith-forge-v1.js'});
const F=sandbox.window.CellboundBlacksmithForge;
assert(F?.create&&F?.record&&F?.quality);
assert.equal(F.STAGES.length,3,'forging has three different actions');
assert.equal([...F.STAGES].map(x=>x.key).join(','),'heat,strike,temper');
let f=F.create();
assert.equal(F.isComplete(f),false);
assert.equal(F.quality(f),null,'no quality before all steps');
assert.equal(F.record(f,NaN),null,'invalid marker rejected');
assert.equal(F.record({...f,stage:3},42),null,'fake completed steps rejected');
for(const step of F.STAGES){f=F.record(f,step.target,50);assert(f);assert.equal(f.results.at(-1).label,'PERFECT')}
assert.equal(F.isComplete(f),true);
assert.equal(F.quality(f),100);
assert.equal(F.record(f,40),null,'completed forge cannot repeat steps');
let rough=F.create();for(const step of F.STAGES)rough=F.record(rough,step.target>50?0:100,1);
assert.equal(F.quality(rough),35,'poor timing still yields basic quality');
let near=F.create();for(const step of F.STAGES)near=F.record(near,step.target+11,1);
assert(F.quality(near)>=65&&F.quality(near)<90,'fine quality is distinct');
// Production consumes heat but never reduces workshop time past the 25% threshold.
const cool=F.advance(100,10000);
assert(Math.abs(cool.heatPct-81)<.01);
assert.equal(cool.activeMs,10000);
const cold=F.advance(100,120000);
assert.equal(cold.heatPct,25);
assert.equal(cold.needsReheat,true);
assert(cold.activeMs>39000&&cold.activeMs<40000,'cold forge must stall focused time');
assert.equal(F.advance(25,2000).activeMs,0,'cold forge makes no work progress');
assert.equal(F.reheat(F.STAGES[0].target,50).heatPct,100,'perfect reheating restores full heat');
assert.equal(F.reheat(F.STAGES[0].target,50).bonusMs,8000,'perfect reheat saves eight seconds');
const weakHeat=F.reheat(100,1);
assert.equal(weakHeat.points,35);
assert.equal(weakHeat.heatPct,51,'rough marker restores much less furnace heat');
assert.equal(weakHeat.bonusMs,0,'rough marker saves no time');
const threshold=F.reheat(F.STAGES[0].target+8.5,1);
assert.equal(threshold.points,80);
assert.equal(threshold.bonusMs,0,'time bonus requires above 80%');
const justAbove=F.reheat(F.STAGES[0].target+8,1);
assert(justAbove.points>80&&justAbove.bonusMs>0&&justAbove.bonusMs<8000,'accuracy scales saved time');
assert(justAbove.heatPct>weakHeat.heatPct&&justAbove.heatPct<100,'accuracy also scales furnace heat');
assert.equal(F.reheat(NaN,50),null,'invalid heating markers are rejected');
assert.equal(F.quality(f),100,'reheating never changes finished batch quality');
const economy=source('economy-v2.js'),css=source('economy-v2.css'),html=source('guild.html');
for(const term of ["craftProject.forge&&!Forge?.isComplete?.(craftProject.forge)","if(craftProject.forge&&!Forge?.isComplete?.(craftProject.forge))return;","project.forge?Forge.quality(project.forge):timedCraftQuality(recipe,prof)","22000*Math.max(1,Math.floor(Number(quantity)||1))","function returnReservedInputs(project)","workshopCraftProject","forgeProjectMarkup(prof)","data-forge-strike","data-forge-position"])assert(economy.includes(term),'integration missing '+term);
assert(economy.includes("prof.name==='Blacksmithing'?5:99"),'only blacksmithing limited to five');
