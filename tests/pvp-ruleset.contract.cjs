'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const sandbox={window:{}};
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.join(__dirname,'..','src','combat','pvp-ruleset-v1.js'),'utf8'),sandbox);
const r=sandbox.window.CellboundPvPRuleset;
assert(r&&r.VERSION==='1.0.0','PvP ruleset must be loaded');
const eq=(actual,expected,label)=>assert.equal(JSON.stringify(actual),JSON.stringify(expected),label);
for(const mode of ['arena','capture-the-flag','king-of-the-hill']){
 const commands=r.rulesFor(mode);
 assert(commands.target.includes('attack-healer'));
 assert(commands.position.includes('fall-back'));
 assert(commands.objective.length>=5);
 assert(r.validateCommand(mode,{category:'position',value:'group-up'}).ok);
}
assert(r.validateCommand('arena',{category:'objective',value:'take-flag'}).ok===false);
assert(r.validateCommand('capture-the-flag',{category:'objective',value:'take-flag'}).ok);
assert(r.validateCommand('king-of-the-hill',{category:'objective',value:'capture-hill'}).ok);
assert(!r.validateCommand('invalid',{category:'target',value:'attack-healer'}).ok);
assert(!r.validateCommand('arena',{category:'target',value:'teleport'}).ok);
assert(!r.validateCommand('arena',{category:'unknown',value:'spread'}).ok);
assert(!r.validateCommand('arena',null).ok);
const blue={team:'blue',position:{x:30,y:40}};
const healer={id:'h',team:'red',role:'healer',alive:true,health:90,maxHealth:100,position:{x:50,y:30}};
const tank={id:'t',team:'red',role:'tank',alive:true,health:100,maxHealth:100,position:{x:50,y:20}};
const damage={id:'d',team:'red',role:'dps',alive:true,health:10,maxHealth:100,position:{x:40,y:40}};
assert.equal(r.selectTarget('attack-healer',blue,[tank,healer,damage])?.id,'h');
assert.equal(r.selectTarget('attack-tank',blue,[tank,healer,damage])?.id,'t');
assert.equal(r.selectTarget('attack-dps',blue,[tank,healer,damage])?.id,'d');
assert.equal(r.selectTarget('focus-low-health',blue,[tank,healer,damage])?.id,'d');
assert.equal(r.selectTarget('attack-healer',blue,[{...healer,stealthed:true},damage])?.id,'d','cannot reveal hidden enemy');
assert.equal(r.selectTarget('attack-healer',blue,[healer,damage],(_,u)=>u.id!=='h')?.id,'d','cannot target through blocked line of sight');
assert.equal(r.selectTarget('attack-healer',blue,[{...healer,team:'blue'},damage])?.id,'d','cannot target own squad');
assert.equal(r.selectTarget('attack-healer',blue,[])||null,null);
eq(r.ratingChange(1000,1000,true).delta,16,'equal rating win');
eq(r.ratingChange(1000,1000,false).delta,-16,'equal rating loss');
eq(r.ratingChange(1000,1200,true).delta,24,'underdog victory');
eq(r.ratingChange(1000,1200,false).delta,-8,'underdog defeat');
eq(r.ratingChange(1000,800,true).delta,8,'favourite victory');
eq(r.ratingChange(1000,800,false).delta,-24,'favourite defeat');
assert.throws(()=>r.ratingChange(1000,1000,'win'));
assert.throws(()=>r.ratingChange(-5,1000,true));
eq(r.queueRange(0),75,'initial search range');
eq(r.queueRange(14),75,'initial range retained');
eq(r.queueRange(15),125,'search expansion');
eq(r.queueRange(150),500,'max range cap');
const a={accountId:'player-one',mode:'arena',format:2,rating:1000,queuedSeconds:45};
const b={accountId:'player-two',mode:'arena',format:2,rating:1150,queuedSeconds:20};
assert.equal(r.mutuallyMatchable(a,b),false,'both accounts must accept the gap');
assert.equal(r.mutuallyMatchable(a,{...b,queuedSeconds:45}),true);
assert.equal(r.mutuallyMatchable(a,{...b,accountId:'player-one'}),false);
assert.equal(r.mutuallyMatchable(a,{...b,format:3}),false);
assert.equal(r.mutuallyMatchable(a,{...b,mode:'capture-the-flag'}),false);
assert.equal(r.arenaUnlock({battlegroundWins:20,gearScores:[90,90],format:2}).unlocked,true);
assert.equal(r.arenaUnlock({battlegroundWins:19,gearScores:[90,90],format:2}).unlocked,false);
assert.equal(r.arenaUnlock({battlegroundWins:20,gearScores:[90,80],format:2}).unlocked,false);
assert.equal(r.arenaUnlock({battlegroundWins:20,gearScores:[90,90],format:3}).unlocked,false);
console.log('PvP ruleset contract passed: mode commands, safe targets/LOS, Elo maths, mutual queue widening and squad gates.');
