'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const js=fs.readFileSync('src/combat/combat-physical-v4.js','utf8'),css=fs.readFileSync('src/combat/combat-physical-v4.css','utf8');
const c={window:{CellboundCombatFX:{},addEventListener(){},matchMedia:()=>({matches:false})},document:{documentElement:{},addEventListener(){}},MutationObserver:class{observe(){}},performance:{now:()=>0},console};
vm.runInNewContext(js,c,{filename:'combat-physical-v4.js'});
const d=c.window.CellboundCombatFX.clarityDescriptor;
const unit=(kind,name)=>({el:{querySelector:()=>null,classList:{contains:x=>x===kind}},spatialMeta:{name},p:{name}});
const player=unit('party','Warrior'),boss=unit('enemy','Deadeye Mercer');
assert.match(d({type:'CAST_START',ability:'Wanted Mark'},boss,player).text,/Deadeye Mercer casting Wanted Mark/);
assert.equal(d({type:'CAST_START',ability:'Wanted Mark'},boss,player).kind,'danger');
assert.match(d({type:'ABILITY_START',ability:'Mortal Strike'},player,boss).text,/Warrior · Mortal Strike/);
assert.equal(d({type:'DAMAGE_DEALT',ability:'Basic Attack'},player,boss),null);
assert.equal(d({type:'INTERRUPT',result:'success'},player,boss).kind,'success');
assert.equal(d({type:'DEFENSIVE_ACTIVATED',ability:'Shield Wall'},player,player).kind,'defense');
assert.match(d({type:'PLAYER_DEFEATED'},boss,player).text,/Warrior down/);
assert(js.includes('initClarity(scene);')&&js.includes('updateClarity(scene,e,u,t);'),'event integration');
assert(js.includes('scene.clarity?.node?.remove();resetClarity(scene);'),'cleanup');
assert(css.includes('.cbl-unit.cbl-primary-target>.cbl-ground:after'),'target cue');
assert(css.includes('.cbl-unit.cbl-danger-cast>.cbl-ground:after'),'danger cue');
assert(css.includes('@media(max-width:680px)'),'mobile readout');
console.log('Combat focus, priority, quieter effects, lifecycle and mobile checks passed.');
