'use strict';
// Technical atlas registration only: no painted pixels are synthesized or recoloured.
const fs=require('node:fs'),path=require('node:path'),sharp=require('sharp');
const sources=require(process.argv.find(a=>a.endsWith('.json'))||'./item-art-sources.json');
const root=path.resolve(__dirname,'..'),out=path.join(root,'assets/items/illustrated-v2');
fs.mkdirSync(out,{recursive:true});
function boundary(expected,radius,limit,score){let best=Math.round(expected),cost=Infinity;for(let n=Math.max(1,Math.round(expected-radius));n<Math.min(limit-1,expected+radius);n++){const v=score(n)+Math.abs(n-expected)*.015;if(v<cost){cost=v;best=n}}return best}
(async()=>{const atlases={};for(const [name,source] of Object.entries(sources)){
 const {data,info}=await sharp(source.path).ensureAlpha().raw().toBuffer({resolveWithObject:true});const W=info.width,H=info.height,cols=name==='heads'?5:6,rows=name==='resources'?6:5;
 const alpha=(x,y)=>data[(y*W+x)*4+3]>96?1:0;
 const ys=[0];for(let r=1;r<rows;r++)ys.push(name==='resources'?Math.round(H*r/rows):boundary(H*r/rows,H/rows*.22,H,y=>{let n=0;for(let x=0;x<W;x++)n+=alpha(x,y);return n}));ys.push(H);
 const cells=[];
 for(let r=0;r<rows;r++){const xs=[0];for(let c=1;c<cols;c++)xs.push(name==='resources'?Math.round(W*c/cols):boundary(W*c/cols,W/cols*.25,W,x=>{let n=0;for(let y=ys[r];y<ys[r+1];y++)n+=alpha(x,y);return n}));xs.push(W);
 for(let c=0;c<cols;c++){
  const bounds=(x0,x1)=>{
   const y0=ys[r],y1=ys[r+1],w=x1-x0,h=y1-y0,seen=new Uint8Array(w*h),parts=[];
   for(let y=y0;y<y1;y++)for(let x=x0;x<x1;x++){
    const index=(y-y0)*w+x-x0;if(seen[index]||!alpha(x,y))continue;
    const queue=[index];seen[index]=1;let l=x,rr=x,t=y,b=y;
    for(let q=0;q<queue.length;q++){const n=queue[q],xx=n%w,yy=Math.floor(n/w);l=Math.min(l,xx+x0);rr=Math.max(rr,xx+x0);t=Math.min(t,yy+y0);b=Math.max(b,yy+y0);
     for(const [dx,dy] of [[1,0],[-1,0],[0,1],[0,-1]]){const nx=xx+dx,ny=yy+dy,ni=ny*w+nx;if(nx<0||nx>=w||ny<0||ny>=h||seen[ni]||!alpha(nx+x0,ny+y0))continue;seen[ni]=1;queue.push(ni)}
    }parts.push({l,rr,t,b,area:queue.length});
   }
   const max=Math.max(...parts.map(p=>p.area)),keep=parts.filter(p=>p.area>=max*.06);if(!keep.length)throw Error('Empty sprite '+name+' '+r+' '+c);
   const l=Math.max(x0,Math.min(...keep.map(p=>p.l))-1),t=Math.max(y0,Math.min(...keep.map(p=>p.t))-1),rr=Math.min(x1,Math.max(...keep.map(p=>p.rr))+2),b=Math.min(y1,Math.max(...keep.map(p=>p.b))+2);return [l,t,rr-l,b-t];
  };
  const rect=bounds(xs[c],xs[c+1]),cell={rect};
  if(['warrior','paladin','hunter','rogue','mage'].includes(name)&&[1,2,5].includes(c)){const mid=boundary((xs[c]+xs[c+1])/2,(xs[c+1]-xs[c])*.12,W,x=>{let n=0;for(let y=ys[r];y<ys[r+1];y++)n+=alpha(x,y);return n});cell.pair=[bounds(xs[c],mid),bounds(mid,xs[c+1])];}
  cells.push(cell);
 }}
 if(!fs.existsSync(path.join(out,name+'.webp'))||process.argv.includes('--encode'))fs.writeFileSync(path.join(out,name+'.webp'),await sharp(source.path).webp({quality:88,alphaQuality:100,effort:4}).toBuffer());
 atlases[name]={src:'assets/items/illustrated-v2/'+name+'.webp',width:W,height:H,cols,rows,cells};
 console.log(name,cols*rows,'sprites',fs.statSync(path.join(out,name+'.webp')).size,'bytes');
}
fs.writeFileSync(path.join(root,'item-atlas-v2.js'),'/* Generated by tools/pack-item-art.cjs. Shared illustrated source for icons and wearables. */\nwindow.CellboundItemAtlases='+JSON.stringify(atlases)+';\n');
})();
